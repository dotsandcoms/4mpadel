import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

// Bundle the browser/report rules into the deployable function so there is one
// maintained implementation. No browser client, credentials or external imports.
export async function buildSummaryBundle(write = true) {
    return build({ entryPoints: [fileURLToPath(new URL('../src/utils/eventFinanceSummary.js', import.meta.url))],
        outfile: fileURLToPath(new URL('../supabase/functions/event-finance-summary/summary.mjs', import.meta.url)),
        bundle: true, format: 'esm', platform: 'neutral', write,
        banner: { js: '// Generated by scripts/build-event-finance-summary.mjs. Do not edit.' },
    });
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await buildSummaryBundle();
