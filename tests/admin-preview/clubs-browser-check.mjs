import puppeteer from 'puppeteer';
import assert from 'node:assert/strict';
const browser = await puppeteer.launch({ headless: true });
try {
  const page = await browser.newPage();
  await page.setRequestInterception(true);
  page.on('request', request => request.url().startsWith('http://127.0.0.1:5175/') || request.url().startsWith('data:') ? request.continue() : request.abort());
  const base = 'http://127.0.0.1:5175/tests/admin-preview/clubs-qa.html';
  const text = () => page.$eval('body', el => el.innerText);
  const click = async label => { const buttons = await page.$$('button'); for (const button of buttons) if ((await button.evaluate(el => el.textContent)) === label) return button.click(); throw new Error(`Missing ${label}`); };
  await page.setViewport({ width: 1280, height: 900 });
  await page.goto(base);
  await page.waitForSelector('.ap-record-loading');
  assert.ok(await page.$eval('.ap-record-loading', el => parseFloat(getComputedStyle(el).paddingLeft) >= 16));
  await page.waitForSelector('tbody tr');
  assert.equal((await page.$$('tbody tr')).length, 10);
  await click('Next');
  assert.equal((await page.$$('tbody tr')).length, 2);
  await page.select('select', 'pending');
  assert.equal((await page.$$('tbody tr')).length, 6);
  assert.match(await text(), /Page 1 of 1/);
  await page.type('input', 'not a club');
  assert.match(await text(), /No matching clubs/);
  await click('Reset filters');
  assert.equal((await page.$$('tbody tr')).length, 10);
  assert.match(await text(), /Not recorded/);
  await page.waitForFunction(() => !document.querySelector('tbody img'));
  await page.click('tbody button');
  await page.waitForFunction(() => document.querySelector('dialog')?.innerText.includes('Synthetic club profile'));
  assert.equal(await page.$eval('dialog h2', el => document.activeElement === el), true);
  assert.equal((await page.$$('dialog a')).length, 0);
  assert.match(await text(), /Coaching/);
  await page.$eval('dialog', async el => Promise.all(el.getAnimations().map(animation => animation.finished)));
  await click('Edit club details');
  await page.waitForSelector('.clubs-full-form input[name="name"]');
  await page.$eval('input[name="name"]', el => { el.focus(); el.select(); });
  await page.keyboard.type('Updated synthetic club');
  await page.$eval('input[name="contact_email"]', el => { el.focus(); el.select(); });
  await page.keyboard.type('club@example.test');
  await click('Review changes');
  assert.match(await text(), /Confirming saves these changes to the live club/);
  assert.equal(await page.evaluate(() => window.clubWrites.length), 0);
  await page.screenshot({ path: '/private/tmp/club-draft-review.png' });
  await click('Cancel');
  await click('Discard changes');
  assert.match(await text(), /Edit club details/);
  await click('Edit club details');
  await page.waitForSelector('.clubs-full-form input[name="contact_email"]');
  await page.$eval('input[name="contact_email"]', el => { el.focus(); el.select(); });
  await page.keyboard.type('club@example.test');
  await click('Review changes');
  await click('Confirm club changes');
  assert.equal(await page.$eval('button[aria-label="Close club details"]', el => el.disabled), true);
  await page.waitForFunction(() => !document.querySelector('.clubs-full-dialog'));
  assert.match(await text(), /club@example.test/);
  assert.equal(await page.evaluate(() => window.clubWrites.length), 1);
  await page.$eval('dialog', async el => Promise.all(el.getAnimations().map(animation => animation.finished)));
  await page.screenshot({ path: '/private/tmp/clubs-details-desktop.png' });
  await page.keyboard.press('Escape');
  assert.equal(await page.$eval('tbody button', el => document.activeElement === el), true);
  const cdp = await page.createCDPSession();
  await cdp.send('Browser.setDownloadBehavior', { behavior: 'deny' });
  await click('Export Excel');
  await page.waitForFunction(() => document.body.innerText.includes('Excel prepared with 12 matching clubs'));
  await page.screenshot({ path: '/private/tmp/clubs-desktop.png', fullPage: true });
  await page.setViewport({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
  assert.equal(await page.$eval('.fo-card', el => getComputedStyle(el).animationName), 'none');
  await page.screenshot({ path: '/private/tmp/clubs-mobile.png', fullPage: true });
  await page.click('tbody button');
  await page.waitForFunction(() => document.querySelector('dialog')?.innerText.includes('Synthetic club profile'));
  assert.ok(await page.$eval('dialog', el => el.getBoundingClientRect().width <= innerWidth));
  await page.screenshot({ path: '/private/tmp/clubs-details-mobile.png' });
  await page.keyboard.press('Escape');
  await page.goto(`${base}?detailError`);
  await page.waitForSelector('tbody button');
  await page.click('tbody button');
  await page.waitForFunction(() => document.querySelector('dialog')?.innerText.includes('Profile unavailable'));
  await page.keyboard.press('Escape');
  for (const [variant, expected] of [['empty', 'No clubs available'], ['error', 'Clubs could not be loaded'], ['denied', 'Platform super-admin access']]) {
    await page.goto(`${base}?${variant}`);
    await page.waitForFunction(expected => document.body.innerText.includes(expected), {}, expected);
  }
  console.log('Clubs browser checks passed: pagination, filters, loader padding, logo fallback, responsive layout, reduced motion, empty/error/access states.');
} finally { await browser.close(); }
